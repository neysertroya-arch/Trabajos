# 5. Conclusiones

# 5.1 Conclusiones principales
# 1. Se logró consolidar la base unificada país-censo integrando FAO WCAD, USDA ERS IAP y World Bank WDI, con N=65 países.
# 2. Se observó heterogeneidad en la prevalencia del arrendamiento, la estructura agraria y el crecimiento de la TFP.
# 3. Correlaciones, gráficos bivariados y ANOVA muestran asociación débil entre prevalencia del arrendamiento y crecimiento TFP post-censo.
# 4. El modelo MCO con controles muestra coeficiente de rental_area_share pequeño e impreciso.

# 5.2 Discusión
# Los resultados son coherentes con la distinción entre prevalencia y efectividad del mercado de arrendamiento.
# La proporción de tierra arrendada por sí sola no garantiza reasignación eficaz ni mayor crecimiento agregado de la TFP.

# 5.3 Recomendación
# Se recomienda incorporar indicadores de calidad del mercado de arrendamiento (duración, seguridad, dirección de transferencias, costos y restricciones).
