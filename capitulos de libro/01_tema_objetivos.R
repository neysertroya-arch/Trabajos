# Tema:
# Arrendamiento de tierras, estructura agraria y crecimiento de la productividad
# total de los factores (TFP) agrícola: evidencia censal entre 65 países.
#
# Objetivo 1:
# Consolidar una base de datos país–censo que integre los indicadores censales de
# la FAO, las series de TFP del USDA ERS y los controles del Banco Mundial, y, a
# partir de ella y de la literatura, diagnosticar los problemas y las
# potencialidades del arrendamiento de tierras como mecanismo de reasignación.
#
# Objetivo 2:
# Estimar un modelo de regresión del crecimiento anual de la TFP agrícola
# sobre la prevalencia del arrendamiento, con controles de estructura agraria y
# desarrollo, errores estándar robustos HC3, un término de interacción con la
# proporción de explotaciones menores de dos hectáreas y un conjunto de
# comprobaciones de robustez.
